import type { GCodeViewerHandle, GCodeViewerOptions } from '@sienci/gviewer/viewer';
import { GCodeVisualizer } from '@sienci/gviewer/react';
import { buildMachineBedOptions } from 'app/features/Visualizer/viewerOptions';
import {
    buildViewerTheme,
    currentViewerThemeName,
} from 'app/features/Visualizer/viewerTheme';
import { useTypedSelector } from 'app/hooks/useTypedSelector';
import { useEffect, useMemo, useRef } from 'react';
import { computeGcodePreviewGeometry } from '../utils/gcodeProcessing';
import { BASE_OPTIONS, selectMachineBedKey } from './Visualizer';

interface Props {
    /** Gcode generated by a tool (e.g. Surfacing); undefined/empty shows a
     * "nothing generated yet" placeholder instead of the viewer. */
    gcode?: string;
}

let previewJobCounter = 0;

/** Renders gcode a pendant tool generated locally (Surfacing, Rotary
 * Surfacing, ...) using the pendant's own top-down WebGL viewer. Unlike the
 * main Visualizer, this never touches the loaded-file redux state, never
 * publishes `file:load`, and never uploads to the controller - a tool preview
 * must not clobber the job the user actually has loaded. */
export default function GcodeToolPreviewVisualizer({ gcode }: Props) {
    const viewerRef = useRef<GCodeViewerHandle>(null);
    const containerRef = useRef<HTMLDivElement>(null);
    const pendingFocusRef = useRef(false);
    const machineBedKey = useTypedSelector(selectMachineBedKey);

    const options = useMemo<Partial<GCodeViewerOptions>>(
        () => ({
            ...BASE_OPTIONS,
            // No live machine position to show here, so the crosshair bit stays off.
            bit: { ...BASE_OPTIONS.bit, enabled: false },
            machineBed: buildMachineBedOptions({ ignoreUserToggle: true }),
            render: {
                antialias: true,
                theme: buildViewerTheme(currentViewerThemeName()),
            },
        }),
        // buildMachineBedOptions reads the store; the key tracks its inputs.
        // eslint-disable-next-line react-hooks/exhaustive-deps
        [machineBedKey],
    );

    const withViewer = (fn: (viewer: GCodeViewerHandle) => void) => {
        const viewer = viewerRef.current;
        if (!viewer) return;
        try {
            fn(viewer);
        } catch {
            // Not mounted yet, or already disposed.
        }
    };

    const focusOrDefer = () => {
        const el = containerRef.current;
        if (!el || el.clientWidth === 0 || el.clientHeight === 0) {
            pendingFocusRef.current = true;
            return;
        }
        pendingFocusRef.current = false;
        withViewer((v) => v.focusToModel());
    };

    useEffect(() => {
        const el = containerRef.current;
        if (!el || typeof ResizeObserver === 'undefined') return;
        const observer = new ResizeObserver(() => {
            if (pendingFocusRef.current) focusOrDefer();
        });
        observer.observe(el);
        return () => observer.disconnect();
    }, []);

    useEffect(() => {
        if (!gcode) {
            pendingFocusRef.current = false;
            withViewer((v) => v.unload());
            return;
        }

        let cancelled = false;
        computeGcodePreviewGeometry({
            content: gcode,
            name: `tool-preview-${++previewJobCounter}.gcode`,
            size: gcode.length,
        })
            .then((geometry) => {
                if (cancelled) return;
                withViewer((v) =>
                    v.loadFromPrecomputedGroups(
                        geometry.svgSegmentGroups ?? [],
                        geometry.svgMeta,
                    ),
                );
                focusOrDefer();
            })
            .catch((error) => {
                console.error('Tool preview visualization failed:', error);
            });

        return () => {
            cancelled = true;
        };
    }, [gcode]);

    return (
        <div ref={containerRef} className="relative w-full h-full">
            <GCodeVisualizer
                ref={viewerRef}
                id="pendant-tool-preview-vis"
                options={options}
                className="w-full h-full"
            />
            {!gcode && (
                <div className="absolute inset-0 flex flex-col items-center justify-center pointer-events-none">
                    <p className="text-content-secondary text-center text-sm px-4">
                        No g-code generated yet.
                        <br /> Please generate g-code first.
                    </p>
                </div>
            )}
        </div>
    );
}
