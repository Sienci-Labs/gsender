import {
    IMPERIAL_UNITS,
    METRIC_UNITS,
    SPIRAL_MOVEMENT,
    START_POSITION_CENTER,
} from 'app/constants';
import defaultState from 'app/store/defaultState';
import Toolpath from '../utils/gcode-toolpath';
import Generator from '../utils/surfacingGcodeGenerator';

describe('Surfacing Output', () => {
    it('should generate gcode for surfacing', () => {
        const gcodeGenerator = new Generator({
            surfacing: defaultState.widgets.surfacing,
            units: 'mm',
        });
        const gcode = gcodeGenerator.generate();
        expect(gcode).toBeDefined();
    });
    it('should generate gcode for surfacing with imperial units', () => {
        const gcodeGenerator = new Generator({
            surfacing: defaultState.widgets.surfacing,
            units: IMPERIAL_UNITS,
        });
        const gcode = gcodeGenerator.generate();
        expect(gcode).toMatch(/G20/);
    });
    it('should generate gcode for surfacing with metric units', () => {
        const gcodeGenerator = new Generator({
            surfacing: defaultState.widgets.surfacing,
            units: METRIC_UNITS,
        });
        const gcode = gcodeGenerator.generate();
        expect(gcode).toMatch(/G21/);
    });
    it('should output the correct gcode for the surfacing', () => {
        const gcodeGenerator = new Generator({
            surfacing: defaultState.widgets.surfacing,
            units: METRIC_UNITS,
        });

        const gcode = gcodeGenerator.generate({ returnArray: true });

        expect(gcode).toEqual(
            expect.arrayContaining([
                '(Header)',
                '(Generated by gSender from Sienci Labs)',
                'G21 ;mm',
                'G90',
                'M3 S17000',
                'G0 X0 Y0',
                'G0 Z3',
                'G1 F2500',
                '(Header End)',
                '',
                '',
                '(*** Layer 1 ***)',
                '(Covering Surfacing Perimeter)',
                '(Ramping into Material)',
                'G91',
                'G1 X28.36 Z-4',
                'G1 X5',
                'G1 X-33.36',
                'G90',
                '(End of Ramping into Material)',
                '',
                'G1 Y-100',
                'G1 X100',
                'G1 Y0',
                'G1 X0',
                '(End of Covering Surfacing Perimeter)',
                '',
                '(Entering Start Position)',
                'G91',
                'G1 Y-8.8',
                'G1 X8.8',
                'G90',
                '(End of Entering Start Position)',
                '',
                'G1 Y-91.2',
                'G1 X91.2',
                'G1 Y-8.8',
                'G1 X17.6',
                '',
                'G1 Y-82.4',
                'G1 X82.4',
                'G1 Y-17.6',
                'G1 X26.4',
                '',
                'G1 Y-73.6',
                'G1 X73.6',
                'G1 Y-26.4',
                'G1 X35.2',
                '',
                'G1 Y-64.8',
                'G1 X64.8',
                'G1 Y-35.2',
                'G1 X44',
                '',
                'G1 Y-56',
                'G1 X56',
                'G1 Y-44',
                'G1 X52.8',
                '',
                'G1 Y-47.2',
                '',
                '(Returning to Zero)',
                'G0 Z3',
                'G0 X0 Y0',
                '(End of Returning to Zero)',
                '',
                '(*** End of Layer 1 ***)',
                '',
                '',
                '(Footer)',
                'M5 ;Turn off spindle',
                '(End of Footer)',
            ]),
        );
    });

    describe('center start spiral', () => {
        type Move = {
            motion: string;
            start: { x: number; y: number; z: number };
            end: { x: number; y: number; z: number };
        };

        const generate = (overrides = {}) =>
            new Generator({
                surfacing: {
                    ...defaultState.widgets.surfacing,
                    length: 100,
                    width: 100,
                    skimDepth: 1,
                    maxDepth: 2,
                    bitDiameter: 22,
                    stepover: 40,
                    type: SPIRAL_MOVEMENT,
                    startPosition: START_POSITION_CENTER,
                    ...overrides,
                },
                units: METRIC_UNITS,
            }).generate({ returnArray: true }) as string[];

        // Simulates the program and records every move
        const simulate = (gcode: string[]): Move[] => {
            const moves: Move[] = [];
            const toolpath = new Toolpath({
                addLine: (
                    modal: { motion: string },
                    start: Move['start'],
                    end: Move['end'],
                ) =>
                    moves.push({
                        motion: modal.motion,
                        start: { ...start },
                        end: { ...end },
                    }),
            });
            toolpath.loadFromStringSync(gcode.join('\n'));
            return moves;
        };

        const cases = [
            { name: 'two layers', overrides: {} },
            { name: 'three layers', overrides: { maxDepth: 3 } },
            {
                name: 'cut direction flipped',
                overrides: { cutDirectionFlipped: true },
            },
        ];

        it.each(cases)(
            'never cuts below max depth ($name)',
            ({ overrides }) => {
                const maxDepth =
                    (overrides as { maxDepth?: number }).maxDepth ?? 2;
                const moves = simulate(generate(overrides));
                expect(Math.min(...moves.map((m) => m.end.z))).toBeCloseTo(
                    -maxDepth,
                );
            },
        );

        it.each(cases)(
            'never rapids below the stock surface ($name)',
            ({ overrides }) => {
                const moves = simulate(generate(overrides));
                const rapidsBelowZero = moves.filter(
                    (m) => m.motion === 'G0' && m.end.z < 0,
                );
                expect(rapidsBelowZero).toEqual([]);
            },
        );

        it.each(cases)(
            'never rapids in XY while below the stock surface ($name)',
            ({ overrides }) => {
                const moves = simulate(generate(overrides));
                const xyRapidsInMaterial = moves.filter(
                    (m) =>
                        m.motion === 'G0' &&
                        m.start.z < 0 &&
                        (m.start.x !== m.end.x || m.start.y !== m.end.y),
                );
                expect(xyRapidsInMaterial).toEqual([]);
            },
        );

        it('moves Z before XY in the header', () => {
            const gcode = generate();
            expect(gcode.indexOf('G0 Z3')).toBeGreaterThan(-1);
            expect(gcode.indexOf('G0 Z3')).toBeLessThan(
                gcode.indexOf('G0 X0 Y0'),
            );
        });
    });
});
